"""Generate frontend/src/lib/api-schema.ts from the backend's OpenAPI schema (no npm package needed).

    backend/.venv/Scripts/python.exe Scripts/gen_api_types.py           write the file
    backend/.venv/Scripts/python.exe Scripts/gen_api_types.py --check   fail if it is out of date (verify.py runs this)

Every Pydantic model the API accepts or returns becomes a TypeScript interface, and `Endpoints` maps
"METHOD /path" to its request body type, so the frontend can type calls from the real backend instead of hand-copied types.
"""
from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "src" / "lib" / "api-schema.ts"


def _openapi() -> dict:
    tmp = tempfile.mkdtemp(prefix="dashtor_openapi_")
    os.environ.update(METADATA_DB=f"{tmp}/m.duckdb", ANALYTICS_DB=f"{tmp}/a.duckdb", UPLOAD_DIR=f"{tmp}/up",
                      DUCKDB_TEMP_DIR=f"{tmp}/s", DISK_USAGE_LIMIT_PCT="99")
    sys.path.insert(0, str(ROOT / "backend"))
    import Main  # noqa: PLC0415 - after the env is set
    return Main.app.openapi()


def _ts(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_ts(s) for s in schema["anyOf"]))
    if "enum" in schema:
        return " | ".join(repr(v).replace("'", '"') for v in schema["enum"])
    t = schema.get("type")
    if t == "array":
        return f"{_ts(schema.get('items', {}))}[]"
    if t == "object":
        extra = schema.get("additionalProperties")
        return f"Record<string, {_ts(extra) if isinstance(extra, dict) else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def render(spec: dict) -> str:
    lines = ["// GENERATED by Scripts/gen_api_types.py from the backend's OpenAPI schema. Do not edit by hand:",
             "// change the Pydantic model, then run `backend/.venv/Scripts/python.exe Scripts/gen_api_types.py`.", ""]
    for name, s in sorted(spec.get("components", {}).get("schemas", {}).items()):
        if name in ("HTTPValidationError", "ValidationError"):
            continue
        if "enum" in s:
            lines.append(f"export type {name} = {_ts(s)};\n")
            continue
        req = set(s.get("required", []))
        lines.append(f"export interface {name} {{")
        for prop, ps in s.get("properties", {}).items():
            key = prop if prop.isidentifier() else f'"{prop}"'
            lines.append(f"  {key}{'' if prop in req else '?'}: {_ts(ps)};")
        lines.append("}\n")
    lines.append("/** Request body type of every endpoint that takes one: Endpoints['POST /api/alerts'] is AlertIn. */")
    lines.append("export interface Endpoints {")
    for path, ops in sorted(spec.get("paths", {}).items()):
        for method, op in sorted(ops.items()):
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            if body:
                lines.append(f'  "{method.upper()} {path}": {_ts(body)};')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render(_openapi())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run backend/.venv/Scripts/python.exe Scripts/gen_api_types.py")
            return 1
        print("API types up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count('export interface')} interfaces)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
